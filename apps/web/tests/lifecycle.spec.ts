import { test, expect } from "@playwright/test";
import path from "node:path";

test("real signup, GPX worker, plan, export, deletion and login", async ({ page }) => {
  const email = `runner-${Date.now()}-${test.info().project.name}@example.com`;
  await page.goto("/");
  await page.getByRole("button", { name: "처음 오셨나요? 회원가입" }).click();
  await page.getByLabel("이름", { exact: true }).fill("테스트 러너");
  await page.getByLabel("이메일", { exact: true }).fill(email);
  await page.getByLabel("비밀번호", { exact: true }).fill("test-runner-password");
  await page.getByRole("button", { name: "회원가입", exact: true }).click();
  await expect(page.getByRole("heading", { name: "테스트 러너님, 오늘도 나의 페이스로." })).toBeVisible();
  await expect(page.getByText("아직 러닝 기록이 없어요")).toBeVisible();
  await page.getByLabel("GPX 업로드", { exact: true }).setInputFiles(path.resolve("../../samples/steady-2km.gpx"));
  await expect(page.getByRole("heading", { name: /러닝 분석/ })).toBeVisible();
  await expect(page.getByText("분석 완료", { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole("heading", { name: "구간별 페이스" })).toBeVisible();
  await expect(page.getByRole("cell", { name: "3 · 부분" })).toBeVisible();
  const nav = page.getByRole("navigation", { name: test.info().project.name.startsWith("mobile") ? "모바일 메뉴" : "주 메뉴" });
  await nav.getByRole("button", { name: "훈련 계획", exact: true }).click();
  await page.getByRole("button", { name: "이번 주 계획 생성" }).click();
  await expect(page.getByText("15분", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "완료 기록", exact: true }).first().click();
  await expect(page.getByRole("button", { name: "완료 취소" })).toBeVisible();
  await nav.getByRole("button", { name: "나의 크루", exact: true }).click();
  await page.getByLabel("새 크루 이름").fill("테스트 베타 크루");
  await page.getByRole("button", { name: "만들기", exact: true }).click();
  await expect(page.getByRole("heading", { name: "테스트 베타 크루", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "7일 초대 코드 발급" }).click();
  await expect(page.getByLabel("초대 코드 (운영자가 직접 전달)")).not.toHaveValue("");
  await page.getByLabel("이 크루에 나의 훈련 요약 공유").check();
  await expect(page.getByText("현재 1명이 동의했습니다.", { exact: false })).toBeVisible();
  await nav.getByRole("button", { name: "설정", exact: true }).click();
  await page.getByLabel("목표 거리 (km)").fill("10");
  await page.getByLabel("목표 시간 (분)").fill("60");
  await page.getByRole("button", { name: "설정 저장" }).click();
  await expect(page.getByText("프로필과 목표를 저장했습니다.", { exact: false })).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "데이터 내보내기" }).click();
  expect((await download).suggestedFilename()).toBe("running-coach-export.zip");
  await page.getByRole("button", { name: "로그아웃", exact: true }).click();
  await expect(page.getByRole("heading", { name: "다시 만나서 반가워요" })).toBeVisible();
  await page.getByLabel("이메일", { exact: true }).fill(email);
  await page.getByLabel("비밀번호", { exact: true }).fill("test-runner-password");
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: "테스트 러너님, 오늘도 나의 페이스로." })).toBeVisible();
  await nav.getByRole("button", { name: "러닝 기록", exact: true }).click();
  await page.getByRole("button", { name: /러닝.*분석 완료/ }).first().click();
  page.once("dialog", d => d.accept());
  await page.getByRole("button", { name: "기록 삭제", exact: true }).click();
  await expect(page.getByText("원본과 분석 기록을 삭제했습니다.", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});

test("invalid GPX shows real server validation error", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "처음 오셨나요? 회원가입" }).click();
  await page.getByLabel("이름", { exact: true }).fill("검증 러너");
  await page.getByLabel("이메일", { exact: true }).fill(`invalid-${Date.now()}@example.com`);
  await page.getByLabel("비밀번호", { exact: true }).fill("test-runner-password");
  await page.getByRole("button", { name: "회원가입", exact: true }).click();
  await expect(page.getByRole("heading", { name: /검증 러너님/ })).toBeVisible();
  await page.getByLabel("GPX 업로드", { exact: true }).setInputFiles({ name: "bad.gpx", mimeType: "application/gpx+xml", buffer: Buffer.from("<gpx/>") });
  await expect(page.getByRole("alert").filter({ hasText: "연속된 트랙 포인트가 2개 이상 필요합니다." })).toBeVisible();
});
